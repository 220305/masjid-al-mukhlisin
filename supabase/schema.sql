-- ==============================================================================
-- SKEMA DATABASE SUPABASE: SISTEM MANAJEMEN MASJID
-- Cocok untuk integrasi Next.js + Supabase + Vercel
-- ==============================================================================

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABEL INVENTARIS (INVENTORIES)
CREATE TABLE IF NOT EXISTS public.inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_barang TEXT NOT NULL,
    jumlah INTEGER NOT NULL DEFAULT 1,
    kondisi TEXT NOT NULL DEFAULT 'baik' CHECK (kondisi IN ('baik', 'pemeliharaan', 'dipinjamkan', 'rusak')),
    lokasi TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABEL KEUANGAN (KAS)
CREATE TABLE IF NOT EXISTS public.kas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keterangan TEXT NOT NULL,
    nominal NUMERIC(15, 2) NOT NULL DEFAULT 0,
    tipe TEXT NOT NULL CHECK (tipe IN ('masuk', 'keluar')),
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABEL AGENDA KHUTBAH & KAJIAN (KHUTBAHS)
CREATE TABLE IF NOT EXISTS public.khutbahs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,
    jenis_kegiatan TEXT NOT NULL DEFAULT 'Shalat Jumat',
    khotib TEXT NOT NULL,
    tema TEXT,
    image TEXT,
    link TEXT,
    status TEXT NOT NULL DEFAULT 'terjadwal' CHECK (status IN ('terjadwal', 'selesai', 'batal')),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexing untuk performa pencarian & sorting
CREATE INDEX IF NOT EXISTS idx_inventories_created ON public.inventories(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_kas_tanggal ON public.kas(tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_khutbahs_tanggal ON public.khutbahs(tanggal ASC);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

ALTER TABLE public.inventories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.khutbahs ENABLE ROW LEVEL SECURITY;

-- 1. Kebijakan Inventaris: Publik bisa membaca (untuk landing page), Pengurus yang login bisa CRUD
DROP POLICY IF EXISTS "Public can view inventories" ON public.inventories;
CREATE POLICY "Public can view inventories" ON public.inventories
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Authenticated users manage inventories" ON public.inventories;
CREATE POLICY "Authenticated users manage inventories" ON public.inventories
    FOR ALL USING (auth.role() = 'authenticated');

-- 2. Kebijakan Kas: Publik bisa membaca (transparansi saldo & arus kas), Pengurus yang login bisa CRUD
DROP POLICY IF EXISTS "Public can view kas" ON public.kas;
CREATE POLICY "Public can view kas" ON public.kas
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Authenticated users manage kas" ON public.kas;
CREATE POLICY "Authenticated users manage kas" ON public.kas
    FOR ALL USING (auth.role() = 'authenticated');

-- 3. Kebijakan Khutbah: Publik bisa membaca jadwal khutbah/kajian, Pengurus yang login bisa CRUD
DROP POLICY IF EXISTS "Public can view khutbahs" ON public.khutbahs;
CREATE POLICY "Public can view khutbahs" ON public.khutbahs
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Authenticated users manage khutbahs" ON public.khutbahs;
CREATE POLICY "Authenticated users manage khutbahs" ON public.khutbahs
    FOR ALL USING (auth.role() = 'authenticated');

-- ==============================================================================
-- STORAGE BUCKET UNTUK POSTER KHUTBAH / KAJIAN
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('khutbah-images', 'khutbah-images', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Kebijakan Storage: Siapa saja bisa melihat gambar (public URL)
DROP POLICY IF EXISTS "Public Access Khutbah Images" ON storage.objects;
CREATE POLICY "Public Access Khutbah Images" ON storage.objects
    FOR SELECT USING (bucket_id = 'khutbah-images');

DROP POLICY IF EXISTS "Authenticated Upload Khutbah Images" ON storage.objects;
CREATE POLICY "Authenticated Upload Khutbah Images" ON storage.objects
    FOR INSERT WITH CHECK (bucket_id = 'khutbah-images' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Authenticated Update Khutbah Images" ON storage.objects;
CREATE POLICY "Authenticated Update Khutbah Images" ON storage.objects
    FOR UPDATE USING (bucket_id = 'khutbah-images' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Authenticated Delete Khutbah Images" ON storage.objects;
CREATE POLICY "Authenticated Delete Khutbah Images" ON storage.objects
    FOR DELETE USING (bucket_id = 'khutbah-images' AND auth.role() = 'authenticated');

