-- SKEMA DATABASE SUPABASE: SISTEM MANAJEMEN TERPADU MASJID AL-MUKHLISIN
-- Dilengkapi Modul Kas, Inventaris, Khutbah, Jamaah, Zakat & Qurban, Petugas Jumat, Wakaf, & Identitas SIMAS
