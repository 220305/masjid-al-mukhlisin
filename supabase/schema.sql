CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. IDENTITAS MASJID & SIMAS KEMENAG RI
CREATE TABLE IF NOT EXISTS public.identitas_masjid (
    id INTEGER PRIMARY KEY DEFAULT 1,
    nama TEXT NOT NULL DEFAULT 'Al-Mukhlisin',
    nomor_id_kemenag TEXT DEFAULT '01.4.13.04.06.000158',
    alamat TEXT DEFAULT 'Kp. Jalan Cagak RT.005 RW.004 Desa Lagadar',
    ketua_dkm TEXT DEFAULT 'Ustadz H. Ahmad Sobari',
    bendahara TEXT DEFAULT 'H. Mulyadi, S.E.',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TABEL KEUANGAN (KAS)
CREATE TABLE IF NOT EXISTS public.kas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    tipe TEXT NOT NULL CHECK (tipe IN ('masuk', 'keluar')),
    kategori TEXT NOT NULL DEFAULT 'Infaq Jumat',
    keterangan TEXT NOT NULL,
    nominal NUMERIC(15, 2) NOT NULL DEFAULT 0,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABEL DATA JAMAAH & WARGA
CREATE TABLE IF NOT EXISTS public.jamaah (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    no_hp TEXT,
    alamat TEXT,
    peran TEXT NOT NULL DEFAULT 'Jamaah' CHECK (peran IN ('Jamaah', 'Pengurus DKM', 'Imam', 'Muadzin', 'Remaja Masjid', 'Donatur')),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABEL AGENDA KHUTBAH & KAJIAN
CREATE TABLE IF NOT EXISTS public.khutbahs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,
    jenis_kegiatan TEXT NOT NULL DEFAULT 'Shalat Jumat',
    khotib TEXT NOT NULL,
    tema TEXT,
    image TEXT,
    link TEXT,
    status TEXT NOT NULL DEFAULT 'terjadwal' CHECK (status IN ('terjadwal', 'selesai', 'batal')),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. TABEL JADWAL PETUGAS JUMAT (IMAM, KHATIB, MUADZIN)
CREATE TABLE IF NOT EXISTS public.petugas_jumat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,
    imam TEXT NOT NULL,
    khatib TEXT NOT NULL,
    muadzin TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. TABEL ZAKAT & QURBAN
CREATE TABLE IF NOT EXISTS public.zakat_qurban (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    nama TEXT NOT NULL,
    jenis TEXT NOT NULL CHECK (jenis IN ('Zakat Fitrah (uang)', 'Zakat Fitrah (beras)', 'Zakat Mal', 'Qurban Sapi (1/7)', 'Qurban Kambing', 'Penyaluran')),
    jumlah_jiwa INTEGER DEFAULT 1,
    beras_kg NUMERIC(10, 2) DEFAULT 0,
    nominal NUMERIC(15, 2) DEFAULT 0,
    keterangan TEXT,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. TABEL INVENTARIS
CREATE TABLE IF NOT EXISTS public.inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_barang TEXT NOT NULL,
    jumlah INTEGER NOT NULL DEFAULT 1,
    kondisi TEXT NOT NULL DEFAULT 'baik' CHECK (kondisi IN ('baik', 'pemeliharaan', 'dipinjamkan', 'rusak')),
    lokasi TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. TABEL WAKAF & DONASI ASET
CREATE TABLE IF NOT EXISTS public.wakaf (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    wakif TEXT NOT NULL,
    jenis TEXT NOT NULL DEFAULT 'Uang' CHECK (jenis IN ('Tanah', 'Bangunan', 'Uang', 'Al-Qur''an', 'Peralatan', 'Lainnya')),
    nilai NUMERIC(15, 2) NOT NULL DEFAULT 0,
    keterangan TEXT,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_kas_tanggal ON public.kas(tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_jamaah_nama ON public.jamaah(nama);
CREATE INDEX IF NOT EXISTS idx_petugas_tanggal ON public.petugas_jumat(tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_zakat_tanggal ON public.zakat_qurban(tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_inventories_created ON public.inventories(created_at DESC);

